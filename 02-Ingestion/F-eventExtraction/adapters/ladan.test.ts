/** Riktig nginx-404 från ladan.se/kalender (HTTP 404, 555 B). */
const NOT_FOUND = `
<html>
<head><title>404 Not Found</title></head>
<body>
<center><h1>404 Not Found</h1></center>
<hr><center>nginx/1.22.1</center>
</body>
</html>
<!-- a padding to disable MSIE and Chrome friendly error page -->
`;

/**
 * FORMATPROBE — inte en riktig Lådan-sida.
 *
 * Lådan använder WordPress, och WordPress markerar daterat innehåll med
 * `<time datetime="YYYY-MM-DD">`. Det finns INGEN sådan markering på sajten
 * i dag (mätt: 0 `<time>`-taggar i den renderade HTML:en), men formatet är
 * standard. Proben bevisar att adaptern kan hitta ett evenemang — att 0
 * events på de riktiga sidorna beror på innehållet, inte på en hårdkodad noll.
 */
const DATED_FORMAT_PROBE = `
<div class="entry-content">
  <time datetime="2026-11-14">Lådan Halloween-party</time>
  <time datetime="2026-11-14">Pubkväll i Vasaparken</time>
</div>
`;

describe('ladan adapter', () => {
  it('matchar bara Lådans egna värdar', () => {
    expect(matches('https://www.ladan.se')).toBe(true);
    expect(matches('https://ladan.se')).toBe(true);
    expect(matches('https://www.ladansthlm.se')).toBe(true);
    expect(matches('https://ladansthlm.se/evenemang')).toBe(true);
    expect(matches('https://example.com/kalender')).toBe(false);
    expect(matches('https://ladan.se.evil.com/')).toBe(false);
    expect(matches('https://notladan.se/')).toBe(false);
    expect(matches('inte en url')).toBe(false);
  });

  it('hittar inga daterade poster på Lådans riktiga sidor', () => {
    expect(findDatedEntries(LADAN_SE_HOME)).toEqual([]);
    expect(findDatedEntries(LADAN_STHLM_HOME)).toEqual([]);
    expect(findDatedEntries(NOT_FOUND)).toEqual([]);
  });

  it('plockar bort HTML-kommentarer (WP-Super-Cache-fällan)', () => {
    const stripped = stripComments(LADAN_STHLM_HOME);
    expect(stripped).not.toContain('WP-Super-Cache');
    expect(stripped).not.toContain('2026-10-24 14:13:43');
    // Kommentaren ska aldrig kunna bli ett evenemang.
    expect(findDatedEntries(LADAN_STHLM_HOME).length).toBe(0);
  });

  it('läser veckans öppettider utan att göra dem till evenemang', () => {
    const hours = findOpeningHours(LADAN_STHLM_HOME);
    expect(hours).toContain('Tisdag - Torsdag 17:00-23:00');
    expect(hours).toContain('Fredag 11:30-00:00');
    expect(hours).toContain('Lördag 12:00-00:00');
  });

  it('ger 0 events på tryckeriets hemsida', () => {
    const res = extract(LADAN_SE_HOME, 'https://www.ladan.se');
    expect(res.events.length).toBe(0);
    expect(res.method).toBe('none');
    expect(res.showUrls).toEqual([]);
  });

  it('ger 0 events på lokalens hemsida (bara öppettider)', () => {
    const res = extract(LADAN_STHLM_HOME, 'https://www.ladansthlm.se');
    expect(res.events.length).toBe(0);
    expect(res.method).toBe('ladan-opening-hours');
    expect(res.showUrls).toEqual([]);
  });

  it('ger 0 events på en 404-sida', () => {
    const res = extract(NOT_FOUND, 'https://www.ladan.se/kalender');
    expect(res.events.length).toBe(0);
    expect(res.method).toBe('none');
  });

  it('hittar daterade evenemang när formatet finns (formatprobe)', () => {
    const res = extract(DATED_FORMAT_PROBE, 'https://www.ladansthlm.se/nyheter');
    expect(res.method).toBe('ladan-dated');
    expect(res.events.length).toBe(2);
    expect(res.events.map((e) => e.title)).toEqual([
      'Lådan Halloween-party',
      'Pubkväll i Vasaparken',
    ]);
    expect(res.events.map((e) => e.date)).toEqual(['2026-11-14', '2026-11-14']);
    expect(res.events[0].venue).toBe('Lådan');
    expect(res.events[0].city).toBe('Stockholm');
    expect(res.events[0].category).toBe('community');
    expect(res.events[0].source).toBe('ladan');
    expect(res.events[0].confidence.signals).toContain('ladan-time-datetime');
  });

  it('gör inget på främmande URL', () => {
    const res = extract(DATED_FORMAT_PROBE, 'https://example.com/kalender');
    expect(res.events.length).toBe(0);
    expect(res.method).toBe('none');
  });

  it('hanterar HTML utan evenemang', () => {
    const res = extract('<html><body>inget</body></html>', 'https://www.ladan.se');
    expect(res.events.length).toBe(0);
    expect(res.method).toBe('none');
  });
});

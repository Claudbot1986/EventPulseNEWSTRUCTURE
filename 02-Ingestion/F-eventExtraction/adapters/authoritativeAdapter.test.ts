/**
 * authoritativeAdapter.test.ts — regeln "adaptern är auktoritativ för sin sajt".
 *
 * Bakgrund (2026-10-24). Mätt på två orelaterade domäner:
 *
 *   folkoperan.se  — adaptern ger 0 events på rot-sidan, men universal-
 *                    heuristiken ger 30 RIKTIGA events ("Jag är Ulla
 *                    Winblad", "Nietzsche kontra Wagner"). Fallbacken är
 *                    här värdefull och MÅSTE stanna kvar.
 *   ladansthlm.se  — adaptern ger korrekt 0 events (sajten publicerar
 *                    inga daterade evenemang), men universalheuristiken
 *                    gör ett FALSKT event av öppettiderna ("Vad är
 *                    Lådan?", 2026-10-27 17:00).
 *
 * Negativ kontroll: folkoperan-fallet är med i testet. Utan det skulle
 * regeln kunna vara "adaptern vinner alltid" — och då hade 30 riktiga
 * events gått förlorade. Testet bevisar att blankettregeln INTE är det
 * som implementerats.
 */

import { describe, expect, it } from 'vitest';
import { ADAPTERS, runAdapters } from './index';
import { extractEvents } from '../universal-extractor';

const LADAN_URL = 'https://www.ladansthlm.se/';

/** Lådans startsida i utdrag: rubrik + veckans öppettider, inga datum. */
const LADAN_HTML = `
  <html><head><title>Lådan</title></head><body>
    <h1>Vad är Lådan?</h1>
    <p>Tisdag - Torsdag 17:00-23:00</p>
    <p>Fredag 11:30-00:00</p>
    <p>Lördag 12:00-00:00</p>
    <!-- Cached page generated by WP-Super-Cache on 2026-10-24 14:13:43 -->
  </body></html>
`;

/**
 * Folkoperans startsida i utdrag: JSON-LD som universalheuristiken hittar,
 * men som folkoperan-adaptern INTE plockar (den letar i annan markup).
 */
const FOLKOPERAN_HTML = `
  <html><head><title>Folkoperan</title>
  <script type="application/ld+json">
  {"@context":"https://schema.org","@type":"Event","name":"Jag är Ulla Winblad",
   "startDate":"2026-11-05T19:00:00+01:00","location":{"name":"Folkoperan"}}
  </script>
  </head><body><h1>Föreställningar</h1></body></html>
`;

describe('authoritative-adapter', () => {
  it('endast Lådan är märkt som auktoritativ', () => {
    const authoritative = ADAPTERS.filter((a) => a.authoritative === true).map((a) => a.name);
    expect(authoritative).toEqual(['ladan']);
  });

  it('Lådan: adaptern matchar och ger 0 events → inget universalfallback', () => {
    const result = runAdapters(LADAN_HTML, LADAN_URL, 'ladan');
    expect(result).not.toBeNull();
    expect(result!.adapter).toBe('ladan');
    expect(result!.events.length).toBe(0);
    expect(result!.authoritative).toBe(true);
  });

  it('Lådan: ingen falsk "Vad är Lådan?" 17:00 i slutresultatet', () => {
    const events = extractEvents(LADAN_HTML, 'ladan', LADAN_URL).events;
    expect(events.length).toBe(0);
    expect(events.some((e) => e.title === 'Vad är Lådan?')).toBe(false);
  });

  it('negativ kontroll: en icke-auktoritativ adapter undertrycker INTE fallbacken', () => {
    // Folkoperan matchar men hittar inget i den här markupen, och är INTE
    // auktoritativ → runAdapters lämnar vidare och universalheuristiken
    // får köra. Hade regeln varit "adaptern vinner alltid" hade detta
    // test fallit — och 30 riktiga folkoperan-events gått förlorade.
    //
    // 2026-10-24 — en matchande men tom adapter rapporteras nu (i stället
    // för att försvinna), så returvärdet är inte längre null. Det som
    // räknas är `authoritative`: false = universalheuristiken får köra.
    const result = runAdapters(FOLKOPERAN_HTML, 'https://www.folkoperan.se/', 'folkoperan');
    expect(result).not.toBeNull();
    expect(result!.adapter).toBe('folkoperan');
    expect(result!.events.length).toBe(0);
    expect(result!.authoritative).toBe(false);
  });

  it('negativ kontroll: folkoperans events finns kvar i slutresultatet', () => {
    const events = extractEvents(FOLKOPERAN_HTML, 'folkoperan', 'https://www.folkoperan.se/').events;
    expect(events.length).toBeGreaterThan(0);
    expect(events.some((e) => e.title === 'Jag är Ulla Winblad')).toBe(true);
  });
});

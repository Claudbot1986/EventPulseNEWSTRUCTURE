/**
 * Lådan adapter — nattlivsverket "Lådan" (Vasaparken, Stockholm).
 *
 * MÄTT (2026-10-24, curl + lokal Playwright/Chromium — ingen ScrapingBee-kredit):
 *
 * 1. Källans registrerade URL `https://www.ladan.se` (HTTP 200, 2 169 B) är
 *    INTE nattlivsverket. Det är "Lådan & Co" — ett tryckeri/designföretag,
 *    Lådan & Co AB, Prästgården, Kårstaby, 186 96 Vallentuna. Sajten är 6
 *    statiska PHP-sidor totalt: hem + /design_original, /web, /pr_media,
 *    /foretaget, /kontakt. /kalender, /evenemang, /event, /program, /matcher,
 *    /biljetter, /utstallningar, /mässor, /nyheter … → HTTP 404. Noll datum
 *    och noll evenemangsord på hela sajten.
 *
 * 2. Den riktiga lokalen i Stockholm ligger på `https://www.ladansthlm.se`
 *    (HTTP 200, 65 kB) — ett WordPress-bryggeri/pub i Vasaparken.
 *    Renderad med Playwright: 4 087 tecken synlig text, 0 ISO-datum,
 *    0 svenska datum och 0 evenemangsord (evenemang/kalender/biljetter/
 *    konsert/event/program/happening). Sajten har 19 sidor, 0 inlägg och
 *    ingen evenemangs-CPT; /evenemang, /kalender, /event, /nyheter → HTTP 404.
 *
 * 3. Det enda tid-liknande innehållet är VECKANS öppettider:
 *      "Tisdag - Torsdag 17:00-23:00", "Fredag 11:30-00:00",
 *      "Lördag 12:00-00:00" samt "Parklådan - Öppet Maj - September."
 *    Det är INTE evenemang: tider utan datum, och en säsong utan startdatum.
 *    Precis som på Nalen riskerar universellextractorn att tolka "17:00" som
 *    ett evenemang — en falsk positiv. Den här adaptern gör det inte.
 *
 * 4. FALLGROP: varje cachead WordPress-sida bär dagens datum i en kommentar:
 *      "<!-- Cached page generated by WP-Super-Cache on 2026-10-24 14:13:43 -->"
 *    En naiv dataskanner gör detta till ett evenemang varje dag. Adaptern
 *    ignorerar därför HTML-kommentarer helt.
 *
 * SLUTSATS: Lådan publicerar idag noll daterade evenemang. Adaptern ger
 * därför 0 events på båda värdarna — mätt, inte gissat — och fångar bara
 * upp ett daterat evenemang om sajten en dag publicerar ett (då via
 * `<time datetime="YYYY-MM-DD">`, som är WordPress standardmarkering).
 *
 * Per CLAUDE.md Generalization Protection Rule: adaptern är isolerad från
 * C0/C1/C2 och gäller ENDAST Lådan.
 */
import { ParsedEventSchema, type ParsedEvent } from '../schema';

const SOURCE_ID = 'ladan';
const VENUE = 'Lådan';
const CITY = 'Stockholm';

/**
 * `ladan.se` = källans registrerade URL (tryckeriet i Kårstaby).
 * `ladansthlm.se` = den riktiga lokalen i Vasaparken, Stockholm.
 */
const HOSTS = new Set([
  'ladan.se',
  'www.ladan.se',
  'ladansthlm.se',
  'www.ladansthlm.se',
]);

export function matches(url: string): boolean {
  try {
    return HOSTS.has(new URL(url).hostname.toLowerCase());
  } catch {
    return false;
  }
}

/**
 * Tar bort HTML-kommentarer. WP-Super-Cache skriver in dagens datum i varje
 * cachead sida ("Cached page generated by WP-Super-Cache on 2026-10-24 ...").
 * Kommentaren är inte evenemangsinformation.
 */
export function stripComments(html: string): string {
  return html.replace(/<!--[\s\S]*?-->/g, ' ');
}

/** Ett daterat evenemang: `<time datetime="2026-11-14">Titel</time>`. */
export interface DatedEntry {
  date: string;
  title: string;
}

const TIME_RX = /<time\b[^>]*\bdatetime="(\d{4}-\d{2}-\d{2})"[^>]*>([\s\S]*?)<\/time>/g;

/** Plockar ut daterade rubriker. Tom lista på Lådans sidor (mätt). */
export function findDatedEntries(html: string): DatedEntry[] {
  const entries: DatedEntry[] = [];
  for (const m of stripComments(html).matchAll(TIME_RX)) {
    const title = m[2].replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
    if (!title) continue;
    entries.push({ date: m[1], title });
  }
  return entries;
}

/**
 * Lådans öppettider — veckans tider utan datum, t.ex.
 * "Tisdag - Torsdag 17:00-23:00". Returneras bara för att dokumentera vad
 * som INTE är evenemang.
 */
export function findOpeningHours(html: string): string[] {
  const hours: string[] = [];
  for (const m of stripComments(html).matchAll(
    /<p>\s*([^<>]*?)\s*(\d{1,2}:\d{2})\s*-\s*(\d{1,2}:\d{2})\s*<\/p>/g
  )) {
    const label = m[1].replace(/&nbsp;/g, ' ').trim();
    if (!label) continue;
    hours.push(`${label} ${m[2]}-${m[3]}`);
  }
  return hours;
}

export interface LadanExtractResult {
  showUrls: string[];
  events: ParsedEvent[];
  method: 'ladan-dated' | 'ladan-opening-hours' | 'none';
}

export function extract(html: string, url: string, source = SOURCE_ID): LadanExtractResult {
  if (!matches(url)) return { showUrls: [], events: [], method: 'none' };

  const events: ParsedEvent[] = [];
  const seen = new Set<string>();

  for (const entry of findDatedEntries(html)) {
    const key = `${entry.title}|${entry.date}`;
    if (seen.has(key)) continue;
    seen.add(key);

    try {
      const evt = ParsedEventSchema.parse({
        title: entry.title,
        date: entry.date,
        venue: VENUE,
        city: CITY,
        url,
        source,
        sourceUrl: url,
        category: 'community',
        confidence: {
          score: 0.7,
          hasTitle: true,
          hasDate: true,
          hasVenue: true,
          hasUrl: true,
          hasDescription: false,
          hasTicketInfo: false,
          signals: ['ladan-time-datetime'],
        },
      });
      events.push(evt);
    } catch {
      /* skip malformed */
    }
  }

  if (events.length > 0) return { showUrls: [], events, method: 'ladan-dated' };

  // Mätt: Lådan har bara veckans öppettider — inga daterade evenemang.
  if (findOpeningHours(html).length > 0) {
    return { showUrls: [], events: [], method: 'ladan-opening-hours' };
  }

  return { showUrls: [], events: [], method: 'none' };
}
